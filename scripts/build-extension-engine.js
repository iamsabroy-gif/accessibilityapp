const fs = require('fs');
const path = require('path');

const projectRoot = path.join(__dirname, '..');
const nativeEnginePath = path.join(__dirname, 'native_engine.js');
const rulesDir = path.join(__dirname, 'rules');
const adaptersDir = path.join(projectRoot, 'extension', 'adapters');
const outputBundlePath = path.join(projectRoot, 'extension', 'content', 'engine.bundle.js');

// Ensure output dir exists
const outputDir = path.dirname(outputBundlePath);
if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true });
}

console.log('Building Chrome Extension engine bundle...');

const nativeEngineSrc = fs.readFileSync(nativeEnginePath, 'utf8');

// Collect inline addRule() code strings — no eval() needed at runtime
const inlineRuleRegistrations = [];
let ruleCount = 0;

// Helper: escape a string for embedding in a JS string literal
function jsStringLiteral(str) {
  if (str == null) return 'undefined';
  return JSON.stringify(String(str));
}

function tagsLiteral(tags) {
  if (!tags || !Array.isArray(tags)) return '[]';
  return JSON.stringify(tags);
}

// Process rules in scripts/rules/
if (fs.existsSync(rulesDir)) {
  const files = fs.readdirSync(rulesDir).sort();
  for (const file of files) {
    if (!file.endsWith('.js')) continue;
    const rulePath = path.join(rulesDir, file);
    const rule = require(rulePath);

    let id, impact, description, help, helpUrl, tags, evaluateFnStr;

    if (rule.type === 'puppeteer') {
      // Find adapter in extension/adapters/
      const adapterPath = path.join(adaptersDir, file);
      if (fs.existsSync(adapterPath)) {
        const adapter = require(adapterPath);
        id = adapter.id || rule.id;
        impact = adapter.impact || rule.impact || 'serious';
        description = adapter.description || rule.description;
        help = adapter.help || rule.help;
        helpUrl = adapter.helpUrl || rule.helpUrl;
        tags = adapter.tags || rule.tags;
        evaluateFnStr = adapter.evaluate.toString();
      } else {
        console.warn(`Warning: Puppeteer rule ${rule.id} (${file}) has no adapter in ${adaptersDir}`);
        continue;
      }
    } else {
      id = rule.id;
      impact = rule.impact || 'serious';
      description = rule.description;
      help = rule.help;
      helpUrl = rule.helpUrl;
      tags = rule.tags;
      evaluateFnStr = rule.evaluate.toString();
    }

    // Emit an inline addRule() call with the evaluate function as real JS code
    inlineRuleRegistrations.push(`
// Rule: ${id}
window.NativeEngine.addRule({
  id: ${jsStringLiteral(id)},
  impact: ${jsStringLiteral(impact)},
  description: ${jsStringLiteral(description)},
  help: ${jsStringLiteral(help)},
  helpUrl: ${jsStringLiteral(helpUrl)},
  tags: ${tagsLiteral(tags)},
  evaluate: ${evaluateFnStr}
});`);
    ruleCount++;
  }
}

const bundleContent = `/**
 * Generated Chrome Extension Native Engine Bundle
 * Auto-generated by scripts/build-extension-engine.js
 * Rules: ${ruleCount}
 * IMPORTANT: No eval() is used — MV3 CSP safe.
 */
(function() {
${nativeEngineSrc}

// --- Register all rules inline (no eval) ---
${inlineRuleRegistrations.join('\n')}

window.__runNativeEngineScan = function() {
  var results = window.NativeEngine.run();

  if (results.violations && results.violations.length > 0) {
    results.violations.forEach(function(v, violIdx) {
      v.violationIndex = violIdx + 1;
      v.nodes.forEach(function(n) {
        if (n.target && n.target[0]) {
          try {
            var el = document.querySelector(n.target[0]);
            if (el) {
              var r = el.getBoundingClientRect();
              var scrollX = window.scrollX || 0;
              var scrollY = window.scrollY || 0;
              n.bbox = {
                x: Math.round(r.left + scrollX),
                y: Math.round(r.top + scrollY),
                width: Math.round(r.width),
                height: Math.round(r.height)
              };
            }
          } catch (_) {}
        }
      });
    });
  }

  var extractedLinks = [];
  try {
    var anchors = Array.from(document.querySelectorAll('a[href]'));
    for (var i = 0; i < anchors.length; i++) {
      var href = anchors[i].getAttribute('href');
      if (!href) continue;
      var lower = href.toLowerCase();
      if (lower.startsWith('mailto:') || lower.startsWith('tel:') || lower.startsWith('javascript:') || lower.startsWith('#')) continue;
      try {
        var u = new URL(href, location.href);
        if (u.protocol === 'http:' || u.protocol === 'https:') {
          extractedLinks.push(u.href);
        }
      } catch (_) {}
    }
  } catch (_) {}

  return {
    url: location.href,
    violations: results.violations,
    passes: results.passes,
    incomplete: results.incomplete,
    links: extractedLinks
  };
};

console.log('[Web Accessibility Scanner] Native Engine loaded with ' + window.NativeEngine.rules.length + ' rules.');
})();
`;

fs.writeFileSync(outputBundlePath, bundleContent, 'utf8');
console.log(`Successfully built engine bundle with ${ruleCount} rules -> ${outputBundlePath}`);
